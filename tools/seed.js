// Deterministic pseudo-randomness. A seed that produces different data each run
// cannot be used to reproduce a bug report, which is most of the value a fixture
// database has.
/**
 * mulberry32 — a small, well-distributed 32-bit PRNG.
 *
 * The first version here was a textbook LCG written as
 * `state = (state * 1103515245 + 12345) & 0x7fffffff`. That multiply reaches
 * about 2.4e18, far past the 2^53 limit at which float64 represents every
 * integer exactly, so the product was ROUNDED before the mask was applied. It
 * was still deterministic, but the sequence was degenerate and lumpy, which
 * showed up as sales clustering on some days and vanishing on others.
 * `Math.imul` does the multiply in true 32-bit integer arithmetic.
 */
function makeRandom(seedValue = 20260101) {
  let state = seedValue >>> 0;
  return function random() {
    state = (state + 0x6d2b79f5) >>> 0;
    let z = state;
    z = Math.imul(z ^ (z >>> 15), z | 1);
    z ^= z + Math.imul(z ^ (z >>> 7), z | 61);
    return ((z ^ (z >>> 14)) >>> 0) / 4294967296;
  };
}
