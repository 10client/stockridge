// TIMESTAMPS
// ---------------------------------------------------------------------
// This schema stores two zones: `sales.sold_at` is WEST AFRICA TIME (it is what
// every trading-day report buckets on) while created_at / updated_at /
// received_at are UTC from datetime('now'). Seeded history has to respect that
// split or the reports it is meant to demonstrate come out an hour off.

/**
 * The trading day this run is anchored to.
 *
 * Set once by main() and read everywhere else. Calling `watToday()` directly at
 * each use meant a run that crossed West Africa midnight part-way through built
 * a database containing two different "todays": a three-sale stub of a day
 * sitting next to a full one, which reads as a hole in the daily-sales chart
 * and looks exactly like a reporting bug. It also made the run irreproducible,
 * because the SET of days generated depended on the second the seed started.
 */
let SEED_TODAY = null;
function seedToday() { return SEED_TODAY || watToday(); }

/** A WAT wall-clock stamp for `seedToday() + dayOffset` at hour:minute. */
function watStamp(dayOffset, hour = 10, minute = 0) {
  return `${addDays(seedToday(), dayOffset)} ${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}:00`;
}

/** The UTC instant of that same WAT moment, for created_at-style columns. */
function utcStamp(dayOffset, hour = 10, minute = 0) {
  return watToUtc(watStamp(dayOffset, hour, minute));
}

/**
 * A WAT sale time on `today - dayOffset`, clamped so it is never in the future.
 *
 * Without the clamp, a seed run shortly after midnight WAT generates "today at
 * 15:00" — which has not happened yet — and the sale engine correctly refuses
 * it as SOLD_AT_IN_FUTURE. That is the engine being right and the fixture being
 * wrong, but it silently thins out today's sales and makes the daily chart dip
 * on the most recent day for no reason anyone could diagnose.
 */
function saleStamp(dayOffset, rng) {
  const nowWat = watNow();
  const stamp = watStamp(-dayOffset, between(rng, 9, 19), between(rng, 0, 59));
  // Both are 'YYYY-MM-DD HH:MM:SS' in the same zone, so a string compare is a
  // chronological compare.
  return stamp > nowWat ? watStamp(0, Number(nowWat.slice(11, 13)), Math.max(0, Number(nowWat.slice(14, 16)) - 2)) : stamp;
}

