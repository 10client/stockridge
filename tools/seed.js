async function seedInstalments(db, rng, days) {
  // Every credit-capable customer is considered, and roughly half get a plan.
  // The earlier version sampled 14 customers and then took a 60% coin flip, so
  // RNG drift between runs produced anywhere from two plans to ten — and with
  // two there is nothing to demonstrate: no arrears, no ageing, no completed
  // plan to compare against. An instalment book is one of the headline features
  // for the Nigerian market, so it gets a floor rather than a dice roll.
  const customers = await db.all('SELECT * FROM customers WHERE credit_limit > 0 AND is_deleted = 0 ORDER BY name');
  let made = 0;
  let considered = 0;
  for (const c of customers) {
    considered += 1;
    // Alternate deterministically, then let the rng vary the terms.
    if (considered % 2 === 0 && !chance(rng, 30)) continue;
    const branch = await db.first('SELECT * FROM branches WHERE id = ?', [c.branch_id]);
    const manager = await db.first("SELECT * FROM users WHERE branch_id = ? AND role = 'MANAGER' LIMIT 1", [c.branch_id]);
    if (!branch || !manager) continue;

    const principal = round2(between(rng, 150000, 1200000));
    const depositPct = 30;
    const deposit = round2(principal * (depositPct / 100));
    const interestPct = 12;
    const interest = round2(principal * (interestPct / 100));
    const tenure = between(rng, 3, 9);
    const startOffset = -between(rng, 10, days);
    const start = addDays(seedToday(), startOffset);
    const planId = newId();
    const schedule = buildSchedule({
      financedAmount: round2(principal - deposit), instalmentCount: tenure,
      scheduleStart: start, frequency: 'MONTHLY',
    });
    const nextPending = schedule.find((s) => s.status === 'PENDING');

    await run(db, 'instalment_plans', {
      id: planId, plan_no: `IP-${String(made + 1).padStart(4, '0')}`,
      branch_id: branch.id, business_id: branch.business_id, customer_id: c.id,
      principal, interest_percent: interestPct, interest_amount: interest,
      total_payable: round2(principal + interest), deposit_amount: deposit,
      tenure_months: tenure, frequency: 'MONTHLY', schedule_start: start, status: 'ACTIVE',
      // Guarantor capture is standard Nigerian practice for work-and-pay, and is
      // the difference between a recoverable and an unrecoverable book.
      guarantor_name: pick(rng, ['Mr. Okonkwo (brother)', 'Mrs. Bello (employer)', 'Chief Adeyemi', 'Alhaji Sani']),
      guarantor_phone: `080${between(rng, 10000000, 99999999)}`,
      guarantor_id_type: pick(rng, ['NIN', 'DRIVERS_LICENCE', 'VOTERS_CARD']),
      guarantor_id_no: String(between(rng, 10000000000, 99999999999)),
      next_due_date: nextPending ? nextPending.dueDate : schedule[schedule.length - 1].dueDate,
      amount_paid: deposit, outstanding: round2(principal + interest - deposit),
      created_by: manager.id, approved_by: manager.id,
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });

    let paid = deposit;
    for (const item of schedule) {
      const past = new Date(`${item.dueDate}T00:00:00Z`).getTime() < Date.now();
      const isPaid = past && chance(rng, 78);
      const amountPaid = isPaid ? item.amountDue : 0;
      await run(db, 'instalment_schedule', {
        id: newId(), plan_id: planId, seq: item.seq, due_date: item.dueDate,
        amount_due: item.amountDue, amount_paid: amountPaid,
        paid_at: isPaid ? utcStamp(-between(rng, 0, days), 12, 0) : null,
        status: isPaid ? 'PAID' : (past ? 'OVERDUE' : 'PENDING'),
        created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
      });
      if (isPaid) paid = round2(paid + amountPaid);
    }
    const outstanding = round2(principal + interest - paid);
    await db.run('UPDATE instalment_plans SET amount_paid = ?, outstanding = ?, status = ? WHERE id = ?',
      [paid, outstanding, outstanding <= 0.005 ? 'COMPLETED' : 'ACTIVE', planId]);
    made += 1;
  }
  return made;
}

async function seedDeposits(db, rng) {
  const customers = await db.all('SELECT * FROM customers WHERE is_deleted = 0 ORDER BY name LIMIT 20');
  let made = 0;
  for (const c of customers) {
    if (!chance(rng, 35)) continue;
    const batch = await db.first(`SELECT sb.*, p.name AS product_name FROM stock_batches sb
        JOIN products p ON p.id = sb.product_id
        WHERE sb.branch_id = ? AND sb.is_deleted = 0 AND sb.status = 'ACTIVE'
          AND sb.quantity - sb.quantity_reserved >= 1
        ORDER BY sb.batch_no LIMIT 1`, [c.branch_id]);
    if (!batch) continue;
    const staff = await db.first("SELECT * FROM users WHERE branch_id = ? AND role IN ('MANAGER','STAFF') LIMIT 1", [batch.branch_id]);
    if (!staff) continue;

    const price = round2(Number(batch.selling_price_per_unit));
    const deposit = round2(price * 0.4);
    const id = newId();
    await run(db, 'deposits', {
      id, branch_id: batch.branch_id, business_id: batch.business_id, customer_id: c.id,
      product_id: batch.product_id, variant_id: batch.variant_id, batch_id: batch.id,
      deposit_type: 'LAYAWAY', quantity: 1, unit_code: 'PIECE', quantity_in_base: 1,
      unit_price: price, total_price: price, deposit_amount: deposit,
      balance_due: round2(price - deposit),
      expires_at: addDays(seedToday(), between(rng, 10, 60)), status: 'ACTIVE',
      created_by: staff.id,
      notes: 'Layaway — customer paying in instalments before collection',
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });
    await run(db, 'deposit_payments', {
      id: newId(), deposit_id: id, branch_id: batch.branch_id, amount: deposit, method: 'CASH',
      reference: `LAY-${String(made + 1).padStart(4, '0')}`, received_by: staff.id,
      received_at: utcStamp(-between(rng, 1, 40), 13, 0),
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });
    // The unit is held against the batch, so the shelf count and the SELLABLE
    // count stay honestly different.
    await db.run("UPDATE stock_batches SET quantity_reserved = quantity_reserved + 1, updated_at = datetime('now') WHERE id = ? AND quantity_reserved < quantity",
      [batch.id]);
    made += 1;
  }
  return made;
}

async function seedWarrantyClaims(db, rng) {
  const serials = await db.all(`SELECT sn.*, p.warranty_months FROM serial_numbers sn
      JOIN products p ON p.id = sn.product_id
      WHERE sn.status = 'SOLD' AND sn.warranty_ends_at IS NOT NULL AND sn.is_deleted = 0
      ORDER BY sn.serial_no LIMIT 40`);
  let made = 0;
  for (const s of serials) {
    if (!chance(rng, 30)) continue;
    const branch = await db.first('SELECT * FROM branches WHERE id = ?', [s.branch_id]);
    const opener = await db.first("SELECT * FROM users WHERE branch_id = ? AND role IN ('MANAGER','STAFF') LIMIT 1", [s.branch_id]);
    if (!branch || !opener) continue;

    // THE OUTCOMES THE SCHEMA DEFINES, NOT THE NOUNS THIS FILE USED TO INVENT.
    //
    // This wrote `REPAIR`, `REPLACE`, `REFUND`, `REJECT` — the vocabulary that existed
    // before migration 0007, which rebuilt the claim table around the six outcomes the
    // resolve route actually accepts: REPAIRED, REPLACED, REFUNDED, REJECTED,
    // SUPPLIER_RETURN, PAID_REPAIR. NOT ONE OF THE FOUR OVERLAPPED, so every seeded
    // claim tripped the new CHECK constraint and **`npm run db:reset` failed outright**
    // — which is the command a new developer runs first, and the one the sample
    // deployment is built from. The migration converted the rows that existed; nothing
    // converted the seeder that writes them.
    //
    // The pairing is the app's own, too: resolving a claim sets its status to CLOSED and
    // records the outcome beside it (see POST /api/warranty-claims/:id/resolve). So a
    // resolved claim here is CLOSED with an outcome, and an open one is somewhere on the
    // way to it — rather than a random status with a random outcome bolted on.
    const OPEN_STATUSES = ['OPEN', 'INSPECTION', 'APPROVED', 'IN_REPAIR'];
    const RESOLUTIONS = ['REPAIRED', 'REPLACED', 'REFUNDED', 'REJECTED', 'SUPPLIER_RETURN', 'PAID_REPAIR'];
    const resolved = chance(rng, 55);
    const status = resolved ? 'CLOSED' : pick(rng, OPEN_STATUSES);
    const resolution = resolved ? pick(rng, RESOLUTIONS) : null;
    const openedOffset = -between(rng, 2, 40);
    await run(db, 'warranty_claims', {
      id: newId(), claim_no: `WC-${String(made + 1).padStart(4, '0')}`,
      business_id: branch.business_id, branch_id: branch.id, sale_id: s.sale_id, serial_id: s.id,
      product_id: s.product_id, variant_id: s.variant_id, customer_id: s.customer_id,
      status, fault_reported: pick(rng, FAULTS),
      fault_found: resolved ? pick(rng, ['Faulty power board', 'Manufacturing defect in panel', 'Compressor failure', 'Confirmed fault, unit replaced']) : null,
      resolution,
      // A rejected claim needs the written explanation the route insists on — without it
      // the demonstration data shows a refusal with no reason, which is the shape the
      // route exists to prevent.
      resolution_notes: resolution === 'REJECTED'
        ? 'Not a manufacturing fault — the unit was connected to an unregulated supply.'
        : null,
      in_warranty: 1, warranty_ends_at: s.warranty_ends_at,
      supplier_id: null, supplier_recovery_amount: 0,
      cost_to_business: resolved ? round2(between(rng, 5000, 120000)) : 0,
      opened_by: opener.id, opened_at: utcStamp(openedOffset, 11, 0),
      resolved_at: resolved ? utcStamp(openedOffset + between(rng, 1, 15), 14, 0) : null,
      closed_at: resolved ? utcStamp(openedOffset + between(rng, 2, 20), 16, 0) : null,
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });
    made += 1;
  }
  return made;
}

/**
 * Progress the delivery jobs the sale engine already created.
 *
 * It does NOT create jobs. `salesService.complete({ deliveryRequired: true })`
 * writes the job and its items in the same transaction as the sale, which is
 * correct — a delivery sale with no job is a promise nobody is tracking. The
 * first version of this function then inserted a SECOND job for the same sale,
 * so forty sales had two jobs each and the dispatch board showed double the
 * work. Seeding on top of a service that already did the job is how fixtures end
 * up contradicting the code they are meant to demonstrate.
 *
 * So this walks the existing jobs and moves them through their lifecycle, which
 * is also more useful: a board full of PENDING jobs demonstrates nothing about
 * delivery tracking, while a mix of delivered, in-transit and failed ones does.
 */
async function seedDeliveries(db, rng) {
  const jobs = await db.all(`SELECT * FROM delivery_jobs WHERE is_deleted = 0 ORDER BY job_no LIMIT 200`);
  let progressed = 0;
  for (const job of jobs) {
    const status = pick(rng, ['SCHEDULED', 'PICKED', 'IN_TRANSIT', 'DELIVERED', 'DELIVERED', 'DELIVERED', 'FAILED']);
    const delivered = status === 'DELIVERED';
    const dayOffset = -between(rng, 0, 8);
    await db.run(`UPDATE delivery_jobs SET
        status = ?, scheduled_at = ?, fuel_cost = ?, distance_km = ?, attempts = ?,
        delivered_at = ?, delivered_to = ?, notes = ?, updated_at = datetime('now')
      WHERE id = ?`, [
      status,
      utcStamp(dayOffset, between(rng, 9, 16), 0),
      delivered ? round2(between(rng, 2000, 25000)) : 0,
      delivered ? between(rng, 5, 90) : null,
      status === 'FAILED' ? between(rng, 1, 3) : delivered ? 1 : 0,
      delivered ? utcStamp(dayOffset, 15, 0) : null,
      delivered ? pick(rng, ['Customer', 'Security guard', 'Housekeeper', 'Site supervisor']) : null,
      status === 'FAILED' ? 'Customer not reachable at the address; will retry.' : null,
      job.id,
    ]);
    if (delivered) {
      await db.run("UPDATE delivery_job_items SET delivered_qty = quantity, updated_at = datetime('now') WHERE delivery_job_id = ?", [job.id]);
    }
    // A delivered sale is complete; one still travelling is not. This is what
    // makes the "awaiting delivery" report meaningful rather than permanently
    // full.
    const saleStatus = delivered ? 'COMPLETED' : 'PENDING_DELIVERY';
    await db.run("UPDATE sales SET status = ?, updated_at = datetime('now') WHERE id = ? AND status <> 'VOIDED'", [saleStatus, job.sale_id]);
    progressed += 1;
  }
  return progressed;
}

/**
 * An intra-business transfer and an INTERCOMPANY one.
 *
 * Moving stock from the electronics business to the furniture business is not a
 * relocation, it is a sale between two legal entities: it has to post a
 * debtor/creditor pair at transfer price, or the two businesses' margins
 * silently cross-subsidise each other and neither P&L is true. That matters the
 * moment the owner asks which of the two shops is actually making money.
 */
async function seedTransfers(db, branches) {
  let made = 0;

  const writeTransfer = async ({ from, to, intercompany, reference, dayOffset, note }) => {
    const manager = await db.first("SELECT * FROM users WHERE branch_id = ? AND role = 'MANAGER' ORDER BY username LIMIT 1", [from.id]);
    // After a few thousand sales most batches are thin, so requiring four units
    // made the transfer silently not happen at all. One unit is enough to
    // demonstrate the accounting, and a transfer that quietly vanishes is worse
    // than a small one.
    const batch = await db.first(`SELECT * FROM stock_batches
        WHERE branch_id = ? AND is_deleted = 0 AND status = 'ACTIVE'
          AND quantity - quantity_reserved >= 1
        ORDER BY quantity - quantity_reserved DESC LIMIT 1`, [from.id]);
    if (!manager || !batch) return false;

    const qty = Math.max(1, Math.min(3, Math.floor(Number(batch.quantity))));
    const unitCost = Number(batch.cost_price_per_unit);
    // An intercompany move carries a markup: it is a sale, not a relocation.
    const unitTransferPrice = intercompany ? round2(unitCost * 1.08) : unitCost;
    const transferId = newId();

    await run(db, 'stock_transfers', {
      id: transferId, reference, from_branch_id: from.id, to_branch_id: to.id,
      from_business_id: from.business_id, to_business_id: to.business_id,
      is_intercompany: intercompany ? 1 : 0,
      transfer_price: round2(qty * unitTransferPrice), status: 'RECEIVED',
      initiated_by: manager.id, initiated_at: utcStamp(dayOffset, 9, 0),
      dispatched_at: utcStamp(dayOffset, 11, 0),
      received_by: manager.id, received_at: utcStamp(dayOffset + 1, 10, 0),
      courier_name: pick(rngStatic, ['GIG Logistics', 'Own vehicle — KLY-482XC', 'ABC Haulage']),
      notes: note,
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });

    const itemId = newId();
    await run(db, 'stock_transfer_items', {
      id: itemId, transfer_id: transferId, product_id: batch.product_id, variant_id: batch.variant_id,
      from_batch_id: batch.id, unit_code: 'PIECE', quantity_sent: qty, quantity_sent_base: qty,
      quantity_received: qty, unit_cost: unitCost, unit_transfer_price: unitTransferPrice,
      received_at: utcStamp(dayOffset + 1, 10, 0), received_by: manager.id,
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });

    // Guarded on the SELLABLE quantity, not the shelf quantity. Reserved units
    // belong to a layaway, and taking them here breaks the stock_batches CHECK
    // (quantity_reserved <= quantity) and aborts the whole seed.
    const moved = await db.run(`UPDATE stock_batches SET quantity = quantity - ?, updated_at = datetime('now')
        WHERE id = ? AND quantity - quantity_reserved >= ?`, [qty, batch.id, qty]);
    if (!moved.changes) return false;
    const toBatchId = newId();
    await run(db, 'stock_batches', {
      id: toBatchId, branch_id: to.id, business_id: to.business_id, product_id: batch.product_id,
      variant_id: batch.variant_id, batch_no: reference, cost_price_per_unit: unitTransferPrice,
      selling_price_per_unit: Number(batch.selling_price_per_unit),
      quantity: qty, quantity_reserved: 0, initial_quantity: qty,
      received_at: utcStamp(dayOffset + 1, 10, 0), received_by: manager.id, status: 'ACTIVE',
      warehouse_zone: 'Transferred in', notes: `Received on ${reference}`,
      created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
    });
    await db.run('UPDATE stock_transfer_items SET to_batch_id = ? WHERE id = ?', [toBatchId, itemId]);

    // Post the accounting for the move. Intra-business is an asset relocation
    // between branches; intercompany is a sale between two entities and posts a
    // real receivable and payable on each side.
    const accountIdsFrom = await glService.loadAccountCodes(db, from.business_id);
    const statements = intercompany
      ? glService.postIntercompanyTransferStatements({
        transfer: { id: transferId, reference },
        fromBusiness: { id: from.business_id, name: await db.scalar('SELECT name FROM businesses WHERE id = ?', [from.business_id]) },
        toBusiness: { id: to.business_id, name: await db.scalar('SELECT name FROM businesses WHERE id = ?', [to.business_id]) },
        fromBranch: from, toBranch: to, value: round2(qty * unitTransferPrice), accountIds: accountIdsFrom, user: manager,
      })
      : glService.postTransferStatements({
        transfer: { id: transferId, reference }, business: { id: from.business_id },
        fromBranch: from, toBranch: to, value: round2(qty * unitCost), accountIds: accountIdsFrom, user: manager,
      });
    for (const st of statements) await db.run(st.sql, st.params);
    return true;
  };

  const electronics = branches.filter((b) => b.code && b.code.startsWith('EL-'));
  if (electronics.length >= 2) {
    if (await writeTransfer({
      from: electronics[0], to: electronics[1], intercompany: false, reference: 'TRF-00001', dayOffset: -5,
      note: 'Branch rebalance ahead of the weekend.',
    })) made += 1;
  }

  const el = branches.find((b) => b.code && b.code.startsWith('EL-'));
  const fu = branches.find((b) => b.code && b.code.startsWith('FU-'));
  if (el && fu) {
    if (await writeTransfer({
      from: el, to: fu, intercompany: true, reference: 'TRF-00002', dayOffset: -10,
      note: 'Intercompany: an appliance sold from the furniture showroom. Treated as a sale between two entities so both P&Ls stay true.',
    })) made += 1;
  }
  return made;
}

async function seedAttendance(db, rng, branches) {
  const users = await db.all("SELECT * FROM users WHERE is_deleted = 0 AND role IN ('MANAGER','STAFF') ORDER BY username");
  let made = 0;
  for (const u of users) {
    const branch = branches.find((b) => String(b.id) === String(u.branch_id));
    if (!branch) continue;
    for (let d = 14; d >= 1; d -= 1) {
      const day = addDays(seedToday(), -d);
      const dow = new Date(`${day}T00:00:00Z`).getUTCDay();
      if (dow === 0 && !chance(rng, 30)) continue; // many shops close or run short on Sundays
      if (!chance(rng, 88)) continue;              // absence is normal

      const inHour = between(rng, 7, 9);
      const outHour = between(rng, 18, 20);
      // Most clock-ins are on site. A few are off-site or have no fix at all,
      // which is what makes the flag-review screen worth demonstrating — and
      // the flags are ADVISORY: a cashier who cannot get a GPS fix is not
      // prevented from opening the shop.
      const roll = rng();
      const onSite = roll < 0.82;
      const noLocation = roll > 0.94;
      const lat = branch.latitude == null ? null : (onSite ? branch.latitude + (rng() - 0.5) * 0.0008 : branch.latitude + (rng() - 0.5) * 0.02);
      const lng = branch.longitude == null ? null : (onSite ? branch.longitude + (rng() - 0.5) * 0.0008 : branch.longitude + (rng() - 0.5) * 0.02);
      const cls = classifyAttendance({
        branch: {
          latitude: branch.latitude, longitude: branch.longitude,
          geofence_radius_meters: branch.geofence_radius_meters,
          name: branch.name, attendance_mode: branch.attendance_mode,
        },
        latitude: noLocation ? null : lat, longitude: noLocation ? null : lng,
        deviceId: null, registeredDeviceIds: [],
      });

      await run(db, 'staff_attendance', {
        id: newId(), user_id: u.id, branch_id: branch.id, business_id: branch.business_id,
        clock_in_at: watStamp(-d, inHour, between(rng, 0, 59)),
        clock_out_at: watStamp(-d, outHour, between(rng, 0, 59)),
        clock_in_method: 'GEOLOCATION',
        clock_in_lat: lat, clock_in_lng: lng, clock_in_device_id: `device-${branch.id.slice(0, 8)}`,
        location_status: cls.locationStatus, distance_meters: cls.distanceMeters,
        device_status: cls.deviceStatus, flagged: cls.flagged, flag_reason: cls.flagReason,
        hours_worked: round2(outHour - inHour + (rng() - 0.5)),
        created_at: sql("datetime('now')"), updated_at: sql("datetime('now')"),
      });
      made += 1;
    }
  }
  return made;
}

