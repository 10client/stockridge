const RAW = Symbol('rawSql');

/** A raw SQL expression, e.g. `sql("datetime('now','-3 days')")`. */
function sql(text, params = []) { return { [RAW]: text, params }; }

/**
 * Build an INSERT from one object.
 *
 * Keys become columns, values become bound parameters — except a `sql()`
 * marker, which is inlined as an expression. The column list and the value list
 * are therefore the same list, and cannot disagree.
 */
function insert(table, obj) {
  const cols = [];
  const vals = [];
  const params = [];
  for (const key of Object.keys(obj)) {
    if (obj[key] === undefined) continue; // omitted means "use the column default"
    cols.push(key);
    const v = obj[key];
    if (v && typeof v === 'object' && v[RAW]) { vals.push(v[RAW]); params.push(...v.params); } else { vals.push('?'); params.push(v); }
  }
  return { sql: `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')})`, params };
}

const run = (db, table, obj) => { const q = insert(table, obj); return db.run(q.sql, q.params); };

