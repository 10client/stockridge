// books that balance — across roughly 90 days of trading history.
//
// WHY 90 DAYS OF HISTORY RATHER THAN A BLANK DATABASE
//
// A blank database cannot demonstrate anything that matters. "Top products this
// quarter", "debtor ageing", "branch comparison", "margin by category", "which
// instalment plans are in arrears" — every one of those needs a body of past
// transactions, and a prospect who sees empty charts sees no product.
//
// The history is generated by driving the REAL services rather than inserting
// rows directly, so seed data has the same integrity as live data. If the sales
// engine has a bug the seed fails loudly instead of producing plausible-looking
// nonsense — which is how several real bugs in the sale path were found.
//
// WHY EVERY INSERT GOES THROUGH insert()
//
// Hand-written column lists drift from hand-written VALUES lists. Three such
// mismatches existed in the sale path and each one meant that code had never
// run. Building the statement from a single object makes the two impossible to
// separate, and `node tools/sql-audit.js` checks the rest of the codebase.
//
// PIN hashes are generated fresh on every run, so no hash is ever committed and
// the demo PINs must never be used on a real deployment.
